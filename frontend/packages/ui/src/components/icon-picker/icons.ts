const ICON_MAP = new Map<string, LucideIconOption>(
  ICON_OPTIONS.map(opt => [opt.name, opt]),
)

export function resolveLucideIcon(name?: string | null): Component {
  const key = (name || '').trim().toLowerCase()
  return ICON_MAP.get(key)?.component ?? Folder
}

export function findLucideIconOption(name?: string | null): LucideIconOption {
  const key = (name || '').trim().toLowerCase()
  return ICON_MAP.get(key) ?? ICON_OPTIONS[0]!
}
